/**
 * 처방 원문의 약재 표기에서 약재명만 남긴다.
 *
 * 왜 필요한가 — 처방 429건의 구성약재를 그대로 세면 574종이 나오는데, 그중
 * 331종이 약재 마스터에 없다. 그런데 그 목록을 열어보면 대부분 약재가 아니다:
 *   薑三片(88건) 棗二枚(63건) 各等分(15건) 一錢二分(10건)
 *   甘草各五分(5건) 神麯炒(7건) 半夏製(3건) 燈心一團(4건)
 * 생강 세 쪽, 대추 두 개 같은 수량 표기와 용량, 법제 접미사가 이름에 붙은
 * 채로 남아 있다. 기존 정리는 `各[\d\w]+` 만 걷어내서 나머지를 놓쳤다.
 *
 * 이 상태면 약재 마스터와 대조가 안 되고, 상호작용·배합금기 판정도 빗나간다.
 * 甘草各五分 은 감초로 읽혀야 하고, 香附子炒 는 향부자로 읽혀야 한다.
 *
 * 법제는 지운다 — 炒(볶음)·製(법제)·炙(굽기) 는 같은 약재의 가공 상태다.
 * 다만 半夏麯(반하국)·神麯(신국) 처럼 麯 가 붙어 별개 약재가 되는 것들은
 * 지우지 않는다. 그래서 麯 는 접미사 목록에서 뺐다.
 */

/** 한자 수사와 아라비아 숫자 */
const NUM = '[一二三四五六七八九十百半數各\\d]';

/** 용량·수량 단위. 錢分兩斤은 용량, 片枚本團合升箇個는 낱개 표기. */
const UNIT = '[錢分兩斤合升片枚本團箇個握把莖匙盞撮枝條]';

/**
 * 법제 접미사. 麯(국)은 별개 약재를 만들므로 넣지 않는다.
 * 尾(당귀미)·身(당귀신)·梢 는 부위 구분이라 남긴다 — 약효가 다르다.
 */
const PROCESS_SUFFIX =
  /(炒焦|炒黑|微炒|酒洗|酒炒|酒浸|酒|童便炒|鹽水炒|鹽|薑製|薑汁炒|醋炒|土炒|蜜炙|水飛|去白|去皮|去心|去節|去蘆|去油|炒|製|制|炮|煨|蒸|焙|煅|炙|鎊|酥|末|飛)+$/;

/**
 * 약재명만 남긴다. 정리할 수 없으면 빈 문자열을 준다 —
 * 용량만 적힌 조각(一錢二分)은 약재가 아니다.
 */
export function cleanHerbName(raw: string): string {
  if (!raw) return '';
  let n = raw.normalize('NFC').replace(/\s+/g, '').trim();

  // 괄호 주석 제거: 當歸(酒洗)
  n = n.replace(/[（(][^）)]*[）)]/g, '');

  // 이름 뒤에 붙은 수량·용량을 걷어낸다. 各五分, 三片, 一錢二分, 二枚 …
  // 뒤에서부터 반복해서 벗긴다(一錢二分 처럼 두 겹인 경우가 있다).
  let prev = '';
  while (prev !== n) {
    prev = n;
    n = n.replace(new RegExp(`${NUM}+${UNIT}$`), '');
    n = n.replace(/各$/, '');
    n = n.replace(/等分$/, '');
  }

  // 법제 접미사 제거
  n = n.replace(PROCESS_SUFFIX, '');
  // 앞에 붙는 법제·상태 접두사: 酒黃芩 → 黃芩, 生茅根 → 茅根
  // 生은 生地黃/生薑처럼 이름의 일부인 경우가 있어 뒤 글자가 2자 이상일 때만 뗀다.
  n = n.replace(/^(酒|炒|鹽|醋|蜜)(?=.{2,})/, '');
  // 少許·適量 같은 분량 표현
  n = n.replace(/(少許|適量|如許|等分)$/, '');

  // 남은 것이 숫자·단위뿐이면 약재가 아니다.
  if (!n || new RegExp(`^${NUM}*${UNIT}*$`).test(n)) return '';

  // 한글도 한자도 없으면 버린다.
  if (!/[가-힣一-鿿]/.test(n)) return '';

  return n;
}

/** 대조용 열쇠 — 마스터와 맞출 때 쓴다. */
export function herbKey(raw: string): string {
  return cleanHerbName(raw).normalize('NFC');
}
