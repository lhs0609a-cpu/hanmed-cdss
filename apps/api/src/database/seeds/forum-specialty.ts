/**
 * 분과를 고른다. 걸리는 것이 없으면 null — 포럼에 올리지 않는다.
 */
export function classifySpecialty(r: Reference): string | null {
  const title = (r.titleKo || r.title || '').trim();
  if (!title) return null;

  for (const s of SPECIALTIES) {
    if (s.hints.some((h) => title.includes(h))) return s.tag;
  }
  return null;
}
