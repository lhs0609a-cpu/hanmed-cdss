/**
 * 논문을 한의과 분과로 가른다.
 *
 * 왜 필요했나: 전문 포럼이 비어 있고, 채울 재료는 KCI 국문 논문 13,644편이
 * 있다. 그런데 그걸 그대로 올리면 임상정보 게시판과 똑같아진다. 분과별로
 * 갈라야 "부인과 자료만 보자" 가 되고, 그때 비로소 포럼이 임상정보와
 * 다른 물건이 된다.
 *
 * category 로는 안 된다. KCI 20,996편 중 14,753편이 'other' 다. 수집기가
 * 침·한약·변증 정도만 가르도록 만들어져 있어 분과 정보가 없다.
 *
 * 그래서 제목에서 읽는다. 지어내는 것이 아니라 이미 제목에 적혀 있는 말을
 * 보는 것이다. 다만 두 가지를 지킨다.
 *
 *   애매하면 버린다. 어느 분과인지 걸리지 않는 논문은 분류하지 않고
 *   포럼에 올리지 않는다. 잘못 붙은 분과는 없는 분과보다 나쁘다 —
 *   부인과를 눌렀는데 침구 논문이 나오면 그 다음부터 태그를 안 믿는다.
 *
 *   먼저 걸리는 것이 이긴다. 아래 순서는 좁은 것에서 넓은 것 순이다.
 *   "사상체질에 따른 요통 치험례" 는 사상체질의학이 아니라 재활의학으로
 *   가는 편이 진료에 맞다. 그래서 증상이 체질보다 앞에 온다.
 */

export interface Specialty {
  /** 태그로 쓸 이름. 게시판에서 사람이 누르는 말이다. */
  tag: string;
  /** 제목에 이 말이 있으면 이 분과로 본다. */
  hints: string[];
}

