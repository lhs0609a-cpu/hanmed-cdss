/**
 * 주소 조각. 한글을 그대로 쓴다 - "요통"으로 검색하는 사람과 주소가 같은
 * 글자를 공유한다. 영문 주제 허브와 같은 `/topics` 아래에 산다.
 */
const KO_TOPIC_PATTERN = /^[가-힣][가-힣A-Za-z0-9]*$/;

export function koTopicSlug(term: string): string | null {
  const trimmed = term.trim();
  if (!trimmed || trimmed.length > 40) return null;
  return KO_TOPIC_PATTERN.test(trimmed) ? trimmed : null;
}
