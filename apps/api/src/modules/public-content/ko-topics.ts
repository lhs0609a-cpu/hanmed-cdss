/**
 * 한국어 주제 허브의 어휘.
 *
 * -- 왜 따로 두는가 --------------------------------------------------
 *
 * 지금 주제 허브(`/topics`)는 논문의 `keywords` 칼럼에서 나온다. 그 칼럼을
 * 전수로 세어 보니 distinct 42,821개 중 한글이 213개뿐이었고, 그나마 주제가
 * 아니라 KCI 연구분야 라벨이었다 - 한의학 20,238 · 방제학 657 · 농학 208 ·
 * 기독교신학 53 · 디자인 20. 한의학 코퍼스에 기독교신학이 붙어 있는 것은
 * 분류 체계가 새어 들어온 것이지 그 논문의 주제가 아니다.
 *
 * 그래서 한의사가 한글로 검색하는데 우리 주제 허브는 영어였다. 그 구멍을
 * 메운다.
 *
 * -- 왜 제목에서 말을 뽑지 않는가 ------------------------------------
 *
 * 형태소 분석기 없이 제목을 쪼개면 쓰레기가 섞이고, 한번 주소가 나간 뒤에는
 * 되돌리기 어렵다. 그래서 통제 어휘만 쓴다 - 우리가 목록을 들고, 그 말이
 * 제목에 글자 그대로 있는 논문만 센다.
 *
 * -- 어휘를 어떻게 골랐는가 ------------------------------------------
 *
 * 후보는 세 곳에서 왔다. 시술·진단·제도 용어(harvest-kci-keywords.ts 가
 * 이미 검증해 둔 것), 처방명(세 글자 이상 한글), 심평원 한의과 상병
 * 한글명 15,923건.
 *
 * 본초 이름은 쓰지 않는다. 제목 검색은 글자만 보므로 동음이의어가 그대로
 * 걸린다 - 실측으로 大棗는 "대조군" 3,634편, 南星은 "남성"(male) 1,125편,
 * 乾薑은 "건강"(health) 725편이었다. 두 글자 처방명도 같은 이유로 뺀다.
 *
 * 거기서 두 번 걸렀다.
 *
 *   1. 기계 - 그 말이 한글 덩어리의 맨 앞에 서는 비율을 쟀다. 조각인 말은
 *      앞에 글자가 더 붙는다. 울증은 1%(우울증), 근종 2%(자궁근종),
 *      비연 0%(예비연구), 구경 5%(연구경향), 진탕 4%(뇌진탕·이진탕).
 *      63개가 여기서 떨어졌다.
 *
 *   2. 사람 - 구조는 멀쩡한데 뜻이 다른 말이 남는다. 기계가 못 가린다.
 *      실제 제목을 읽고 뺐다.
 *        주사 168편 -> 코르티코스테로이드 주사 (酒齄 아님)
 *        소양 124편 -> 소양인 처방 (瘙痒 아님)
 *        유산  77편 -> 유산소 운동
 *        단독  69편 -> "한약 단독 치료"(monotherapy) (丹毒 아님)
 *        호산  33편 -> 호산구의 조각
 *        진전  30편 -> "연구 진전"(progress) (振顫 아님)
 *      그 밖에 복수·질식·기미·비해·하소와, 주제가 아닌 말
 *      (유발·상태·기타·실천·설정·근위·주체·풍선·실비·유치·후유·경증·어지).
 *
 * 새 말을 넣을 때도 이 두 단계를 거친다. 기계만 믿으면 "단독 치료"가
 * 丹毒 허브에 들어가고, 사람만 믿으면 "예비연구"가 鼻淵으로 들어간다.
 */

